#!/bin/bash
set -euo pipefail
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOSQL
CREATE USER authentik WITH PASSWORD '${AUTHENTIK_DB_PASSWORD}';
CREATE DATABASE authentik OWNER authentik;
CREATE USER wiki WITH PASSWORD '${WIKI_DB_PASSWORD}';
CREATE DATABASE wiki OWNER wiki;
CREATE USER patrimonio WITH PASSWORD '${PATRIMONIO_DB_PASSWORD}';
CREATE DATABASE patrimonio OWNER patrimonio;
CREATE USER chamados WITH PASSWORD '${CHAMADOS_DB_PASSWORD}';
CREATE DATABASE chamados OWNER chamados;
EOSQL